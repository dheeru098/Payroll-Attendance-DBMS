-- PostgreSQL 15+; run as database administrator in a NEW database.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA payroll_app;
SET search_path TO payroll_app, public;
CREATE TABLE employee (
 employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name text NOT NULL CHECK (btrim(full_name) <> ''),
 department text NOT NULL CHECK (btrim(department) <> ''),
 email text NOT NULL UNIQUE,
 hire_date date NOT NULL,
 login_name text UNIQUE
);
CREATE TABLE leave_request (
 leave_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 employee_id integer NOT NULL REFERENCES employee(employee_id),
 start_date date NOT NULL, end_date date NOT NULL,
 status text NOT NULL CHECK (status IN ('Pending','Approved','Rejected')),
 reason text NOT NULL,
 CHECK (end_date >= start_date),
 EXCLUDE USING gist (employee_id WITH =, daterange(start_date,end_date,'[]') WITH &&)
 WHERE (status = 'Approved')
);
CREATE TABLE attendance (
 attendance_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 employee_id integer NOT NULL REFERENCES employee(employee_id),
 work_date date NOT NULL,
 status text NOT NULL CHECK (status IN ('Present','Absent','Leave')),
 check_in time, check_out time,
 UNIQUE(employee_id,work_date),
 CHECK ((status='Present' AND check_in IS NOT NULL AND check_out IS NOT NULL AND check_out > check_in)
 OR (status IN ('Absent','Leave') AND check_in IS NULL AND check_out IS NULL))
);
CREATE TABLE salary (
 employee_id integer REFERENCES employee(employee_id),
 effective_month date NOT NULL CHECK (EXTRACT(DAY FROM effective_month)=1),
 basic numeric(12,2) NOT NULL CHECK (basic > 0),
 allowance numeric(12,2) NOT NULL CHECK (allowance >= 0),
 PRIMARY KEY(employee_id,effective_month)
);
CREATE TABLE payroll (
 employee_id integer NOT NULL REFERENCES employee(employee_id),
 pay_month date NOT NULL CHECK (EXTRACT(DAY FROM pay_month)=1),
 salary_month date NOT NULL,
 working_days integer NOT NULL CHECK (working_days > 0),
 paid_days integer NOT NULL CHECK (paid_days >= 0 AND paid_days <= working_days),
 gross numeric(12,2) NOT NULL CHECK (gross >= 0),
 tax numeric(12,2) NOT NULL CHECK (tax >= 0 AND tax <= gross),
 net numeric(12,2) GENERATED ALWAYS AS (gross-tax) STORED,
 calculated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(employee_id,pay_month),
 FOREIGN KEY(employee_id,salary_month) REFERENCES salary(employee_id,effective_month),
 CHECK (salary_month <= pay_month)
);
COMMIT;
